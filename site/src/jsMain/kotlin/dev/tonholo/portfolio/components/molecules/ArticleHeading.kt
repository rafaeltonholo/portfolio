private const val SECTION_LINK_CLASS = "article-section-link"

/**
 * Marks links inside an article that bring their own style, so the prose link style (underline, accent colour)
 * skips them.
 */
const val ARTICLE_PLAIN_LINK_CLASS = "article-plain-link"
private const val HEADING_LEVEL_3 = 3
private const val HEADING_LEVEL_4 = 4
private const val HEADING_LEVEL_5 = 5
private const val COPIED_FEEDBACK_MS = 1500
private const val SECTION_LINK_ICON_REM = 0.8
private const val SECTION_LINK_GAP_EM = 0.4
private const val TOUCH_LINK_OPACITY = 0.6
private const val LINK_FADE_MS = 150

/**
 * A markdown heading with a link icon that copies a shareable URL to that section. The icon appears on hover
 * and on keyboard focus, and stays faintly visible on touch screens, which have no hover.
 *
 * @param level heading level, from 1 to 6.
 * @param id the heading's anchor id, as generated by the markdown converter.
 * @param modifier optional [Modifier] applied to the heading element.
 * @param content the heading text.
 */
@Composable
fun ArticleHeading(
    level: Int,
    id: String,
    modifier: Modifier = Modifier,
    content: @Composable () -> Unit,
) {
    val attrs: AttrsScope<HTMLHeadingElement>.() -> Unit = ArticleHeadingStyle.toModifier().then(modifier).toAttrs {
        id(id)
    }
    val body: @Composable () -> Unit = {
        content()
        SectionLink(id = id)
    }
    when (level) {
        1 -> H1(attrs) { body() }
        2 -> H2(attrs) { body() }
        HEADING_LEVEL_3 -> H3(attrs) { body() }
        HEADING_LEVEL_4 -> H4(attrs) { body() }
        HEADING_LEVEL_5 -> H5(attrs) { body() }
        else -> H6(attrs) { body() }
    }
}

@Composable
private fun SectionLink(id: String) {
    val strings = LocalStrings.current.articleBody
    var copied by remember { mutableStateOf(false) }
    var resetTimer by remember { mutableStateOf<Int?>(null) }
    DisposableEffect(Unit) {
        onDispose { resetTimer?.let { window.clearTimeout(it) } }
    }
    A(
        href = "#$id",
        attrs = SectionLinkStyle
            .toModifier()
            .classNames(SECTION_LINK_CLASS, ARTICLE_PLAIN_LINK_CLASS)
            .ariaLabel(if (copied) strings.sectionLinkCopied else strings.sectionLink)
            .onClick { event ->
                event.preventDefault()
                jumpToAnchor(id)
                val location = window.location
                val url = "${location.origin}${location.pathname}#$id"
                if (runCatching { window.navigator.clipboard.writeText(url) }.isFailure) return@onClick
                copied = true
                resetTimer?.let { window.clearTimeout(it) }
                resetTimer = window.setTimeout({ copied = false }, COPIED_FEEDBACK_MS)
            }
            .toAttrs(),
    ) {
        PhosphorIcon(name = if (copied) "check" else "link", size = SECTION_LINK_ICON_REM.cssRem)
    }
}

/** Reveals the section link while the heading is hovered. */
val ArticleHeadingStyle = CssStyle {
    cssRule(":hover > .$SECTION_LINK_CLASS") {
        Modifier.opacity(1)
    }
}

/** The section link icon next to a heading: hidden until hover or focus, faint on touch screens. */
val SectionLinkStyle = CssStyle {
    base {
        val muted = if (colorMode == ColorMode.DARK) Muted.dark else Muted.light
        Modifier
            .margin(left = SECTION_LINK_GAP_EM.em)
            .color(muted.muted)
            .textDecorationLine(TextDecorationLine.None)
            .opacity(0)
            .transition(Transition.of(property = "opacity", duration = LINK_FADE_MS.ms))
    }
    hover {
        val accent = if (colorMode == ColorMode.DARK) AccentMint.dark else AccentMint.light
        Modifier.color(accent.accent)
    }
    focusVisible {
        Modifier.opacity(1)
    }
    cssRule(
        mediaQuery = CSSMediaQuery.MediaFeature(name = "hover", value = StylePropertyValue(value = "none")),
    ) {
        Modifier.opacity(TOUCH_LINK_OPACITY)
    }
}
